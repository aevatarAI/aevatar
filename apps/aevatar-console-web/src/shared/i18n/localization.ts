function normalizeLocale(value: string | null | undefined): AppLocale | null {
  const normalized = value?.trim().replace("_", "-").toLowerCase();
  if (!normalized) {
    return null;
  }

  if (normalized.startsWith("zh")) {
    return "zh-CN";
  }

  if (normalized.startsWith("en")) {
    return "en-US";
  }

  return null;
}

export function resolveAppLocale(): AppLocale {
  if (typeof window === "undefined") {
    return defaultLocale;
  }

  const params = new URLSearchParams(window.location.search);
  const queryLocale = normalizeLocale(params.get("locale"));
  if (queryLocale) {
    return queryLocale;
  }

  const storedLocale = normalizeLocale(
    window.localStorage?.getItem("aevatar.locale"),
  );
  if (storedLocale) {
    return storedLocale;
  }

  return defaultLocale;
}

export function getSupportedAppLocales(): readonly AppLocale[] {
  return supportedLocales;
}

export function translate(
  key: string,
  values?: TranslationValues,
  locale: AppLocale = resolveAppLocale(),
): string {
  const template =
    dictionaries[locale][key] ?? dictionaries[defaultLocale][key] ?? key;

  if (!values) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (match, token) => {
    const value = values[token];
    return value === undefined || value === null ? match : String(value);
  });
}

export function useTranslation(locale?: AppLocale): {
  readonly locale: AppLocale;
  readonly t: (key: string, values?: TranslationValues) => string;
} {
  const resolvedLocale = React.useMemo(
    () => locale ?? resolveAppLocale(),
    [locale],
  );

  const t = React.useCallback(
    (key: string, values?: TranslationValues) =>
      translate(key, values, resolvedLocale),
    [resolvedLocale],
  );

  return {
    locale: resolvedLocale,
    t,
  };
}
